ALTER TABLE purchase_request_items
    ADD COLUMN received_quantity INTEGER NOT NULL DEFAULT 0;

ALTER TABLE purchase_request_items
    DROP CONSTRAINT ck_purchase_request_items_status,
    DROP CONSTRAINT ck_purchase_request_items_received_on,
    ADD CONSTRAINT ck_purchase_request_items_status
        CHECK (status IN ('PENDING', 'PURCHASED', 'PARTIALLY_RECEIVED', 'RECEIVED', 'CANCELLED')),
    ADD CONSTRAINT ck_purchase_request_items_received_quantity
        CHECK (received_quantity >= 0 AND received_quantity <= quantity),
    ADD CONSTRAINT ck_purchase_request_items_receipt_state
        CHECK (
            (status = 'PENDING' AND received_quantity = 0)
            OR (status = 'PARTIALLY_RECEIVED' AND received_quantity > 0 AND received_quantity < quantity)
            OR (status = 'RECEIVED' AND received_quantity = quantity AND received_on IS NOT NULL)
            OR status IN ('PURCHASED', 'CANCELLED')
        );

CREATE TABLE purchase_request_item_receipts (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    purchase_request_item_id BIGINT NOT NULL,
    received_quantity INTEGER NOT NULL,
    received_on DATE NOT NULL,
    checked_by VARCHAR(150) NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_purchase_request_item_receipts_item
        FOREIGN KEY (purchase_request_item_id)
        REFERENCES purchase_request_items (id)
        ON DELETE CASCADE,
    CONSTRAINT ck_purchase_request_item_receipts_quantity CHECK (received_quantity > 0)
);

CREATE TABLE purchase_request_history (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    purchase_request_id BIGINT NOT NULL,
    action VARCHAR(40) NOT NULL,
    performed_by VARCHAR(150) NOT NULL,
    details TEXT NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_purchase_request_history_request
        FOREIGN KEY (purchase_request_id)
        REFERENCES purchase_requests (id)
        ON DELETE CASCADE
);

CREATE INDEX idx_purchase_request_item_receipts_item_id ON purchase_request_item_receipts (purchase_request_item_id);
CREATE INDEX idx_purchase_request_history_request_id ON purchase_request_history (purchase_request_id, created_at DESC);
